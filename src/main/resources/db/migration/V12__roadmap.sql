-- La Roadmap est la liste ordonnée des Jalons d'une version de Spec (D-19). Critères d'acceptation dans le corps du Ticket.
CREATE TABLE jalon (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spec_id  bigint NOT NULL REFERENCES spec (id) ON DELETE CASCADE,
    ordre    integer NOT NULL,
    titre    TEXT    NOT NULL,
    jira_key TEXT
);

CREATE TABLE ticket (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jalon_id   bigint NOT NULL REFERENCES jalon (id) ON DELETE CASCADE,
    ordre      integer NOT NULL,
    titre      TEXT    NOT NULL,
    corps      TEXT    NOT NULL DEFAULT '',
    exigences  TEXT    NOT NULL DEFAULT '',
    jira_key   TEXT
);

CREATE TABLE ticket_bloque (
    ticket_id     bigint NOT NULL REFERENCES ticket (id) ON DELETE CASCADE,
    bloque_par_id bigint NOT NULL REFERENCES ticket (id) ON DELETE CASCADE,
    PRIMARY KEY (ticket_id, bloque_par_id),
    CHECK (ticket_id <> bloque_par_id)
);
